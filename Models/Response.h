#pragma once

// Тип результата ввода, используемый Hand и Game.
enum class Response {
    OK,      // Нейтральное состояние: команда ещё не получена.
    BACK,    // Отмена предыдущего хода по истории состояний доски.
    REPLAY,  // Начать новую партию с исходной расстановки.
    QUIT,    // Закрыть окно и выйти из приложения.
    CELL     // Пользователь выбрал клетку игровой доски.
};
